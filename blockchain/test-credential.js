/**
 * Test Script: Submit and Verify a Creditworthiness Credential
 * This demonstrates the full credential issuance flow
 */

const { ethers } = require("hardhat");

async function main() {
  console.log("\n🧪 Testing Creditworthiness Credential System");
  console.log("=".repeat(60));

  // Get contract addresses from deployment
  const VERIFIER_ADDRESS = "0x5FbDB2315678afecb367f032d93F642f64180aa3";
  const SBT_ADDRESS = "0xe7f1725E7734CE288F8367e1Bb143E90bb3F0512";
  const REGISTRY_ADDRESS = "0x9fE46736679d2D9a65F0992F2272dE9f3c7fa6e0";

  // Get signers
  const [deployer, user1, user2] = await ethers.getSigners();
  console.log("\n👤 Test Accounts:");
  console.log(`   Deployer: ${deployer.address}`);
  console.log(`   User 1:   ${user1.address}`);
  console.log(`   User 2:   ${user2.address}`);

  // Get contract instances
  const Registry = await ethers.getContractFactory("CreditworthinessRegistry");
  const registry = Registry.attach(REGISTRY_ADDRESS);

  const SBT = await ethers.getContractFactory("CredentialSBT");
  const sbt = SBT.attach(SBT_ADDRESS);

  console.log("\n📊 Initial State:");
  const initialCounter = await registry.credentialIdCounter();
  console.log(`   Total credentials issued: ${initialCounter}`);

  // Mock ZK proof data (in production, this would be generated by the prover)
  console.log("\n🔐 Submitting Credential with ZK Proof...");
  console.log("   (Using mock verifier - all proofs accepted in test mode)");
  
  const proof_a = [1, 2];
  const proof_b = [[1, 2], [3, 4]];
  const proof_c = [5, 6];
  const publicSignals = [
    50000,  // minIncome (borrower proves income >= $50,000)
    700,    // minCreditScore (borrower proves score >= 700)
    30      // minPaymentRatio (borrower proves debt-to-income <= 30%)
  ];
  const policyId = 1;
  const expirationDays = 90;

  console.log("\n   Public Thresholds (revealed on-chain):");
  console.log(`   • Minimum Income:        $${publicSignals[0].toLocaleString()}`);
  console.log(`   • Minimum Credit Score:  ${publicSignals[1]}`);
  console.log(`   • Max Payment Ratio:     ${publicSignals[2]}%`);
  console.log(`   • Policy ID:             ${policyId}`);
  console.log(`   • Expiration:            ${expirationDays} days`);

  // Submit credential as User 1
  console.log("\n   Submitting from User 1's address...");
  const tx = await registry.connect(user1).submitCredential(
    proof_a,
    proof_b,
    proof_c,
    publicSignals,
    policyId,
    expirationDays
  );

  const receipt = await tx.wait();
  console.log(`   ✅ Transaction confirmed in block ${receipt.blockNumber}`);
  console.log(`   Gas used: ${receipt.gasUsed.toString()}`);

  // Get the credential ID
  const credentialId = await registry.credentialIdCounter();
  console.log(`   📜 Credential ID: ${credentialId}`);

  // Fetch credential details
  console.log("\n📋 Credential Details:");
  const credential = await registry.getCredential(credentialId);
  console.log(`   ID:           ${credential.id}`);
  console.log(`   Borrower:     ${credential.borrower}`);
  console.log(`   Policy ID:    ${credential.policyId}`);
  console.log(`   State:        ${["PENDING", "VERIFIED", "ACTIVE", "EXPIRED", "REVOKED"][credential.state]}`);
  console.log(`   Issued At:    ${new Date(Number(credential.issuedAt) * 1000).toLocaleString()}`);
  console.log(`   Expires At:   ${new Date(Number(credential.expiresAt) * 1000).toLocaleString()}`);
  console.log(`   Proof Hash:   ${credential.proofHash}`);

  // Check if credential is valid
  const isValid = await registry.isCredentialValid(credentialId);
  console.log(`\n✅ Credential Valid: ${isValid}`);

  // Check SBT ownership
  console.log("\n🎫 Soulbound Token (SBT) Status:");
  const sbtBalance = await sbt.balanceOf(user1.address);
  console.log(`   User 1 SBT Balance: ${sbtBalance}`);
  
  const sbtOwner = await sbt.ownerOf(credentialId);
  console.log(`   SBT Owner: ${sbtOwner}`);
  console.log(`   Matches User 1: ${sbtOwner === user1.address}`);

  // Try to transfer SBT (should fail - it's soulbound!)
  console.log("\n🚫 Testing Soulbound Property (transfer should fail):");
  try {
    await sbt.connect(user1).transferFrom(user1.address, user2.address, credentialId);
    console.log("   ❌ ERROR: Transfer succeeded (should have failed!)");
  } catch (error) {
    console.log("   ✅ Transfer correctly blocked - token is soulbound");
    console.log(`   Error: ${error.message.split('\n')[0]}`);
  }

  // Get all active credentials for User 1
  console.log("\n📚 User 1's Active Credentials:");
  const activeCredentials = await registry.getActiveCredentials(user1.address);
  console.log(`   Total active credentials: ${activeCredentials.length}`);
  activeCredentials.forEach((id, index) => {
    console.log(`   ${index + 1}. Credential ID: ${id}`);
  });

  // Test issuer authorization (only admin can do this)
  console.log("\n👨‍⚖️  Testing Issuer Authorization:");
  const isIssuer = await registry.isAuthorizedIssuer(user2.address);
  console.log(`   User 2 is authorized issuer: ${isIssuer}`);
  
  console.log("\n   Authorizing User 2 as issuer...");
  await registry.connect(deployer).authorizeIssuer(user2.address);
  const isIssuerNow = await registry.isAuthorizedIssuer(user2.address);
  console.log(`   ✅ User 2 is now authorized issuer: ${isIssuerNow}`);

  console.log("\n" + "=".repeat(60));
  console.log("🎉 All Tests Passed Successfully!");
  console.log("=".repeat(60));
  console.log("\n📌 Summary:");
  console.log("   ✅ Credential submitted with ZK proof");
  console.log("   ✅ Soulbound token minted to borrower");
  console.log("   ✅ Credential data stored on-chain");
  console.log("   ✅ Transfer protection working");
  console.log("   ✅ Issuer authorization working");
  console.log("\n💡 Note: Using mock ZK verifier for testing");
  console.log("   Install Circom for real cryptographic proofs\n");
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error(error);
    process.exit(1);
  });
